"""
Cubicraftia 2D icon + title artwork generator (Pillow, no GPU).

Generates every PNG asset listed in docs/art-direction-brief.md §3 except the
avatar preset thumbnails (those come from scripts/generate_builder.py).

Output paths follow the brief verbatim — replacing the 1×1 transparent stubs
that v1.0 ships with. Re-running is safe; outputs are overwritten.

Anchored to the Cubicraftia palette (cubicraftia.tres / art-direction-brief §1.3).

Usage:
    python3 scripts/generate_icons.py

License: GPL-3.0-or-later.
"""

import os
import math
from PIL import Image, ImageDraw, ImageFilter, ImageFont

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICON_DIR = os.path.join(REPO, "assets", "textures", "icons")
FONT_REG = os.path.join(REPO, "assets", "fonts", "NotoSans-Regular.ttf")
FONT_BOLD = os.path.join(REPO, "assets", "fonts", "NotoSans-SemiBold.ttf")

# Palette (RGBA tuples)
NAVY = (27, 44, 86, 255)
BRICK_WHITE = (241, 240, 234, 255)
ACCENT = (245, 195, 13, 255)
DEST_RED = (214, 56, 40, 255)
GREEN = (61, 181, 96, 255)
AMBER = (232, 137, 12, 255)
GRAY = (107, 114, 128, 255)
TRANS = (0, 0, 0, 0)


# ─── Helpers ──────────────────────────────────────────────────────────────────

def new_img(size):
    """Create a transparent RGBA image at 3× the target size for supersampling."""
    return Image.new("RGBA", (size * 3, size * 3), TRANS)


def downsample(img, target_size):
    """High-quality downsample with LANCZOS."""
    return img.resize((target_size, target_size), Image.LANCZOS)


def save(img, name, target_size):
    """Save a 3×-authored image to icon directory at target_size."""
    path = os.path.join(ICON_DIR, name)
    out = downsample(img, target_size) if img.size[0] != target_size else img
    out.save(path, optimize=True)
    write_license(path)
    return path


def save_explicit(img, name):
    """Save image at its native size (no downsample)."""
    path = os.path.join(ICON_DIR, name)
    img.save(path, optimize=True)
    write_license(path)
    return path


def write_license(png_path):
    """SPDX sidecar in project convention."""
    with open(png_path + ".license", "w") as fh:
        fh.write(
            "SPDX-FileCopyrightText: 2026 Cubicraftia contributors\n"
            "SPDX-License-Identifier: GPL-3.0-or-later\n"
            "Generated by scripts/generate_icons.py.\n"
        )


def soft_shadow(img, offset_y=4, blur=4, opacity=64):
    """Drop a soft shadow underneath the alpha mask (returns new RGBA)."""
    shadow = Image.new("RGBA", img.size, TRANS)
    alpha = img.split()[3]
    shadow.paste((0, 0, 0, opacity), (0, offset_y), alpha)
    shadow = shadow.filter(ImageFilter.GaussianBlur(blur))
    out = Image.alpha_composite(shadow, img)
    return out


# ─── Icon constructors ────────────────────────────────────────────────────────

def icon_friends(target=32):
    img = new_img(target)
    d = ImageDraw.Draw(img)
    # Two cube-head silhouettes — back one slightly smaller/dimmer
    w = img.size[0]
    # Back head
    bx, by, bs = w * 0.55, w * 0.30, w * 0.32
    d.rounded_rectangle((bx, by, bx + bs, by + bs), radius=bs * 0.18, fill=(*BRICK_WHITE[:3], 180))
    # Body for back head
    d.rounded_rectangle((bx - bs * 0.1, by + bs, bx + bs * 1.1, w * 0.95), radius=w * 0.05, fill=(*BRICK_WHITE[:3], 180))
    # Front head
    fx, fy, fs = w * 0.10, w * 0.35, w * 0.38
    d.rounded_rectangle((fx, fy, fx + fs, fy + fs), radius=fs * 0.18, fill=BRICK_WHITE)
    # Front body
    d.rounded_rectangle((fx - fs * 0.1, fy + fs, fx + fs * 1.1, w * 0.97), radius=w * 0.05, fill=BRICK_WHITE)
    return save(img, "icon_friends.png", target)


def icon_signal(active_bars, target=16):
    img = new_img(target)
    d = ImageDraw.Draw(img)
    w = img.size[0]
    # 3 vertical bars increasing in height. Colors: signal_1 amber, signal_2 yellow, signal_3 green.
    bar_w = w * 0.18
    gap = w * 0.08
    base_y = w * 0.85
    heights = [w * 0.30, w * 0.55, w * 0.80]
    total_w = bar_w * 3 + gap * 2
    start_x = (w - total_w) / 2
    colors = [AMBER, ACCENT, GREEN]
    for i in range(3):
        x = start_x + i * (bar_w + gap)
        y_top = base_y - heights[i]
        if i < active_bars:
            color = colors[active_bars - 1]
        else:
            color = (*BRICK_WHITE[:3], 60)
        d.rounded_rectangle((x, y_top, x + bar_w, base_y), radius=bar_w * 0.2, fill=color)
    return save(img, f"icon_signal_{active_bars}.png", target)


def icon_mute(target=16):
    img = new_img(target)
    d = ImageDraw.Draw(img)
    w = img.size[0]
    # Speaker silhouette (trapezoid)
    pts = [(w * 0.20, w * 0.40), (w * 0.36, w * 0.40),
           (w * 0.50, w * 0.25), (w * 0.50, w * 0.75),
           (w * 0.36, w * 0.60), (w * 0.20, w * 0.60)]
    d.polygon(pts, fill=(*BRICK_WHITE[:3], 200))
    # Slash
    d.line((w * 0.60, w * 0.25, w * 0.85, w * 0.78), fill=DEST_RED, width=int(w * 0.07))
    return save(img, "icon_mute.png", target)


def icon_freeze(target=16):
    img = new_img(target)
    d = ImageDraw.Draw(img)
    w = img.size[0]
    cx, cy = w / 2, w / 2
    r = w * 0.40
    # 6-point snowflake
    for angle_deg in range(0, 360, 60):
        a = math.radians(angle_deg)
        x2 = cx + math.cos(a) * r
        y2 = cy + math.sin(a) * r
        d.line((cx, cy, x2, y2), fill=ACCENT, width=int(w * 0.08))
        # Small branches at 2/3 of the spike
        bx = cx + math.cos(a) * r * 0.6
        by = cy + math.sin(a) * r * 0.6
        for branch_offset in (40, -40):
            ba = math.radians(angle_deg + branch_offset)
            bx2 = bx + math.cos(ba) * r * 0.25
            by2 = by + math.sin(ba) * r * 0.25
            d.line((bx, by, bx2, by2), fill=ACCENT, width=int(w * 0.05))
    return save(img, "icon_freeze.png", target)


def icon_spinner(target=32):
    img = new_img(target)
    d = ImageDraw.Draw(img)
    w = img.size[0]
    cx, cy = w / 2, w / 2
    outer = w * 0.40
    inner = w * 0.28
    # Dashed arc — 8 segments, alternating opacity
    for seg in range(8):
        a0 = seg * 45
        a1 = a0 + 30
        opacity = int(255 * (seg / 8.0)) + 30   # gradient
        d.arc(
            (cx - outer, cy - outer, cx + outer, cy + outer),
            start=a0, end=a1,
            fill=(*BRICK_WHITE[:3], min(opacity, 255)),
            width=int(w * 0.10),
        )
    return save(img, "icon_spinner.png", target)


