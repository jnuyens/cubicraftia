def ftue_arrow(target=128):
    img = new_img(target)
    d = ImageDraw.Draw(img)
    w = img.size[0]
    # Chunky downward arrow — shaft + arrowhead, slight tilt
    pad = w * 0.20
    shaft_w = w * 0.18
    cx = w / 2
    shaft_top = w * 0.10
    shaft_bot = w * 0.62
    head_top = w * 0.55
    head_bot = w * 0.85
    head_w = w * 0.45
    # Outline navy
    arrow_pts_outer = [
        (cx - shaft_w, shaft_top),
        (cx + shaft_w, shaft_top),
        (cx + shaft_w, head_top),
        (cx + head_w, head_top),
        (cx, head_bot),
        (cx - head_w, head_top),
        (cx - shaft_w, head_top),
    ]
    # Draw outline first (slightly larger polygon for stroke effect)
    stroke = int(w * 0.03)
    d.polygon(arrow_pts_outer, fill=NAVY)
    # Then fill arrow_pts shrunk by stroke
    arrow_pts_inner = []
    for x, y in arrow_pts_outer:
        # shrink towards center
        dx = x - cx
        dy = y - w * 0.5
        scale = 0.90
        arrow_pts_inner.append((cx + dx * scale, w * 0.5 + dy * scale))
    d.polygon(arrow_pts_inner, fill=ACCENT)
    # Eye + smile on arrowhead
    eye_x, eye_y = cx - w * 0.06, head_top + w * 0.05
    d.ellipse((eye_x - w * 0.025, eye_y - w * 0.025, eye_x + w * 0.025, eye_y + w * 0.025), fill=NAVY)
    # Smile arc
    d.arc((cx - w * 0.10, head_top + w * 0.02, cx + w * 0.08, head_top + w * 0.16),
          start=10, end=170, fill=NAVY, width=int(w * 0.015))
    return save(img, "ftue_arrow.png", target)


# ─── Title screen artwork ─────────────────────────────────────────────────────

def title_bg(target=512):
    """Seamlessly tileable brick-stud pattern for title background."""
    img = Image.new("RGB", (target, target), NAVY[:3])
    d = ImageDraw.Draw(img)
    stud_pitch = target // 32   # 32 studs across
    stud_d = int(stud_pitch * 0.70)
    # Slightly different alpha tints for visual interest
    for sy in range(0, target + stud_pitch, stud_pitch):
        for sx in range(0, target + stud_pitch, stud_pitch):
            # Offset every other row to suggest stagger
            x_off = (stud_pitch // 2) if (sy // stud_pitch) % 2 == 1 else 0
            cx = sx + x_off
            cy = sy
            # Wrap for seamless tiling
            cx %= target
            cy %= target
            # Vary color: most navy-tinted, occasional yellow / brick-white accent
            seed = (cx * 31 + cy * 17) % 100
            if seed < 70:
                color = (40, 60, 100)   # slightly lighter navy
            elif seed < 90:
                color = (60, 80, 130)   # even lighter navy
            elif seed < 96:
                color = BRICK_WHITE[:3]
            else:
                color = ACCENT[:3]
            d.ellipse((cx - stud_d // 2, cy - stud_d // 2, cx + stud_d // 2, cy + stud_d // 2), fill=color)
    img.save(os.path.join(ICON_DIR, "title_bg.png"), optimize=True)
    write_license(os.path.join(ICON_DIR, "title_bg.png"))


def wordmark():
    """Cubicraftia wordmark — NotoSans SemiBold at 96 px, 1024x256."""
    img = Image.new("RGBA", (1024, 256), TRANS)
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype(FONT_BOLD, 110)
    except Exception:
        font = ImageFont.load_default()
    text = "Cubicraftia"
    # Centre measure
    bbox = d.textbbox((0, 0), text, font=font)
    tw = bbox[2] - bbox[0]
    th = bbox[3] - bbox[1]
    tx = (1024 - tw) // 2 - bbox[0]
    ty = (256 - th) // 2 - bbox[1]
    d.text((tx, ty), text, font=font, fill=BRICK_WHITE)
    # Accent yellow underline on final stroke (under the "a")
    underline_y = ty + th + 8
    underline_x_start = tx + int(tw * 0.85)
    underline_x_end = tx + tw
    d.rectangle((underline_x_start, underline_y, underline_x_end, underline_y + 4), fill=ACCENT)
    img.save(os.path.join(ICON_DIR, "cubicraftia_wordmark.png"), optimize=True)
    write_license(os.path.join(ICON_DIR, "cubicraftia_wordmark.png"))


def world_thumb_placeholder():
    """Default world thumbnail — 2x4 brick on navy with ? overlay."""
    img = Image.new("RGB", (256, 144), NAVY[:3])
    d = ImageDraw.Draw(img)
    # Dotted-line border
    for x in range(0, 256, 8):
        d.point((x, 4), fill=BRICK_WHITE[:3])
        d.point((x, 139), fill=BRICK_WHITE[:3])
    for y in range(0, 144, 8):
        d.point((4, y), fill=BRICK_WHITE[:3])
        d.point((251, y), fill=BRICK_WHITE[:3])
    # 2x4 brick silhouette in centre
    bw, bh = 90, 35
    bx, by = (256 - bw) // 2, (144 - bh) // 2 - 5
    d.rounded_rectangle((bx, by, bx + bw, by + bh), radius=4, fill=ACCENT[:3])
    # 8 studs on top (2x4)
    for col in range(4):
        for row in range(2):
            sx = bx + 10 + col * 20
            sy = by + 8 + row * 14
            d.ellipse((sx - 4, sy - 4, sx + 4, sy + 4), fill=(180, 140, 5))
    # "?" overlay below
    try:
        font = ImageFont.truetype(FONT_BOLD, 32)
    except Exception:
        font = ImageFont.load_default()
    d.text((118, 95), "?", font=font, fill=BRICK_WHITE[:3])
    img.save(os.path.join(ICON_DIR, "world_thumb_placeholder.png"), optimize=True)
    write_license(os.path.join(ICON_DIR, "world_thumb_placeholder.png"))


# ─── Main ─────────────────────────────────────────────────────────────────────

def main():
    os.makedirs(ICON_DIR, exist_ok=True)
    print(f"Cubicraftia icon generator → {ICON_DIR}\n")

    generated = []

    # Network status icons
    for n in (1, 2, 3):
        p = icon_signal(n)
        generated.append(p)
        print(f"  ✓ {os.path.basename(p)}")

    for name, fn in [
        ("icon_friends.png",       icon_friends),
        ("icon_mute.png",          icon_mute),
        ("icon_freeze.png",        icon_freeze),
        ("icon_spinner.png",       icon_spinner),
        ("icon_error.png",         icon_error),
        ("icon_warning.png",       icon_warning),
        ("icon_email.png",         icon_email),
        ("icon_check.png",         icon_check),
        ("icon_plus.png",          icon_plus),
        ("icon_arrow_down.png",    icon_arrow_down),
        ("icon_dice.png",          icon_dice),
        ("ftue_arrow.png",         ftue_arrow),
    ]:
        p = fn()
        generated.append(p)
        print(f"  ✓ {name}")

    # Title screen artwork
    title_bg()
    generated.append(os.path.join(ICON_DIR, "title_bg.png"))
    print("  ✓ title_bg.png (512x512 seamless brick pattern)")

    wordmark()
    generated.append(os.path.join(ICON_DIR, "cubicraftia_wordmark.png"))
    print("  ✓ cubicraftia_wordmark.png (1024x256)")

    world_thumb_placeholder()
    generated.append(os.path.join(ICON_DIR, "world_thumb_placeholder.png"))
    print("  ✓ world_thumb_placeholder.png (256x144)")

    print(f"\nGenerated {len(generated)} assets.")


if __name__ == "__main__":
    main()
